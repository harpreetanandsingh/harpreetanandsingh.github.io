"""Builds _data/hero_tail.yml: SVG paths for P(|R| > x), daily US stock returns vs a Normal.

Input: CRSP daily stock file (crsp.dsf) with a RET column, read in chunks.
Only aggregate survival probabilities on a fixed grid are written; no security-level rows.
Usage: python3 scripts/make_hero_tail.py /path/to/crsp_daily.csv
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import norm

W, H = 320, 200            # SVG viewBox
L, R, T, B = 34, 8, 8, 26  # plot margins
X_MAX = 0.30
LOG_MIN = -6               # y axis: 10^-6 .. 10^0
GRID = np.linspace(0, X_MAX, 61)
EDGES = np.concatenate([GRID, [np.inf]])


def px(x):
    return L + x / X_MAX * (W - L - R)


def py(p):
    return T + (0 - np.log10(p)) / (0 - LOG_MIN) * (H - T - B)


def path(xs, ps):
    pts = [(px(x), py(p)) for x, p in zip(xs, ps) if np.isfinite(p) and p >= 10 ** LOG_MIN]
    return "M" + " L".join(f"{a:.1f},{b:.1f}" for a, b in pts)


def main(csv):
    n, s1, s2 = 0, 0.0, 0.0
    hist = np.zeros(len(GRID), dtype=np.int64)
    first, last = None, None
    for chunk in pd.read_csv(csv, usecols=["date", "RET"], dtype={"RET": "string"}, chunksize=5_000_000):
        r = pd.to_numeric(chunk["RET"], errors="coerce").to_numpy()
        ok = np.isfinite(r)
        r = r[ok]
        n += r.size
        s1 += r.sum()
        s2 += np.square(r).sum()
        hist += np.histogram(np.abs(r), bins=EDGES)[0]
        d = chunk["date"].to_numpy()
        first = d[0] if first is None else first
        last = d[-1]
    mu = s1 / n
    sd = np.sqrt(s2 / n - mu ** 2)
    # counts of |R| >= grid[i]: reverse cumulative sum of bin counts
    counts = hist[::-1].cumsum()[::-1]
    emp = np.where(counts >= 5, counts / n, np.nan)
    nrm = norm.cdf((-GRID - mu) / sd) + norm.sf((GRID - mu) / sd)

    i10 = np.searchsorted(GRID, 0.10)
    print(f"n={n:,}  dates {first}..{last}  mean={mu:.5f} sd={sd:.4f}  "
          f"P(|R|>10%) emp={emp[i10]:.5f} normal={nrm[i10]:.2e}")

    yticks = "\n".join(
        f"  - {{ y: {py(10.0 ** k):.1f}, label: \"10^{k}\" }}" for k in range(LOG_MIN, 1)
    )
    xticks = "\n".join(
        f"  - {{ x: {px(v):.1f}, label: \"{int(round(v * 100))}%\" }}" for v in (0, 0.1, 0.2, 0.3)
    )
    out = Path(__file__).resolve().parent.parent / "_data" / "hero_tail.yml"
    out.write_text(
        "# Generated by scripts/make_hero_tail.py from CRSP daily returns. Aggregate survival curve only.\n"
        f"width: {W}\nheight: {H}\n"
        f"plot: {{ left: {L}, right: {W - R}, top: {T}, bottom: {H - B} }}\n"
        f"observations: \"{n / 1e6:.0f} million\"\n"
        f"years: \"{str(first)[:4]}–{str(last)[:4]}\"\n"
        f"empirical: \"{path(GRID, emp)}\"\n"
        f"normal: \"{path(GRID, nrm)}\"\n"
        f"yticks:\n{yticks}\n"
        f"xticks:\n{xticks}\n",
        encoding="utf-8",
    )
    print("wrote", out)


if __name__ == "__main__":
    main(sys.argv[1])
