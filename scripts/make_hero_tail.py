"""Builds _data/hero_tail.yml: SVG paths for P(|R| > x), empirical vs Normal.

Only aggregate survival probabilities on a fixed grid are written; no firm-level rows.
Usage: python3 scripts/make_hero_tail.py /path/to/model_data.csv
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import norm

W, H = 320, 200            # SVG viewBox
L, R, T, B = 34, 8, 8, 26  # plot margins
X_MAX = 0.8
LOG_MIN = -5               # y axis: 10^-5 .. 10^0
GRID = np.linspace(0, X_MAX, 81)


def px(x):
    return L + x / X_MAX * (W - L - R)


def py(p):
    return T + (0 - np.log10(p)) / (0 - LOG_MIN) * (H - T - B)


def path(xs, ps):
    pts = [(px(x), py(p)) for x, p in zip(xs, ps) if np.isfinite(p) and p >= 10 ** LOG_MIN]
    return "M" + " L".join(f"{a:.1f},{b:.1f}" for a, b in pts)


def main(csv):
    r = pd.read_csv(csv, usecols=["date", "return_1m"])["return_1m"].dropna().to_numpy()
    a = np.abs(r)
    mu, sd = r.mean(), r.std()
    counts = np.array([(a > x).sum() for x in GRID])
    emp = np.where(counts >= 5, counts / len(a), np.nan)  # stop where < 5 firm-months remain
    nrm = norm.cdf((-GRID - mu) / sd) + norm.sf((GRID - mu) / sd)

    i30 = np.searchsorted(GRID, 0.3)
    print(f"n={len(r):,}  sd={sd:.4f}  P(|R|>30%) emp={emp[i30]:.5f} normal={nrm[i30]:.6f} "
          f"ratio={emp[i30] / nrm[i30]:.1f}x")

    yticks = "\n".join(
        f"  - {{ y: {py(10.0 ** k):.1f}, label: \"10^{k}\" }}" for k in range(LOG_MIN, 1)
    )
    xticks = "\n".join(
        f"  - {{ x: {px(v):.1f}, label: \"{int(v * 100)}%\" }}" for v in (0, 0.2, 0.4, 0.6, 0.8)
    )
    out = Path(__file__).resolve().parent.parent / "_data" / "hero_tail.yml"
    out.write_text(
        "# Generated by scripts/make_hero_tail.py. Aggregate survival curve only.\n"
        f"width: {W}\nheight: {H}\n"
        f"plot: {{ left: {L}, right: {W - R}, top: {T}, bottom: {H - B} }}\n"
        f"firm_months: \"{len(r):,}\"\n"
        f"empirical: \"{path(GRID, emp)}\"\n"
        f"normal: \"{path(GRID, nrm)}\"\n"
        f"yticks:\n{yticks}\n"
        f"xticks:\n{xticks}\n",
        encoding="utf-8",
    )
    print("wrote", out)


if __name__ == "__main__":
    main(sys.argv[1])
